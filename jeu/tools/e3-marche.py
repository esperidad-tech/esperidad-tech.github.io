"""Enquête 3 : les autres chemins du marché aux fleurs du Barde (tools/e3-barde.py joue le meilleur).
1. « Marché conclu ! » tout de suite, Iris fâchée, Basile au prix fort le matin, puis encore l'après-midi (dans sa conversation),
   le maire avec 4 bouquets (pas d'or) ;
2. Fortuné sait qu'on veut la lanterne (« magnifique ! ») : 4 pièces pour l'avoir ; Iris l'après-midi seulement (elle marchande alors) ;
3. le Barde ferme la fenêtre du maire sans la lire : il revient ; il touche un villageois avant : le maire d'abord.
   BRUMEVAL_DIST=<dossier construit> python3 tools/e3-marche.py"""
import sys, os, json
from playwright.sync_api import sync_playwright
ICI = os.path.dirname(os.path.abspath(__file__))
URL = 'file://' + os.path.join(os.path.abspath(os.environ.get('BRUMEVAL_DIST') or os.path.join(ICI, '..', 'dist')), 'index.html') + '#test'
erreurs, echecs = [], []

def verifier(cond, quoi):
    print('  ✓' if cond else '  ✗', quoi)
    if not cond: echecs.append(quoi)
def ev(pg, act, data=None):
    pg.evaluate(f"() => {{ M.A['{act}']({{dataset:{json.dumps(data or {})}, closest:function(){{ return null; }}}}); }}"); pg.wait_for_timeout(100)
def modal(pg): return pg.evaluate("() => M.UI.modal ? JSON.parse(JSON.stringify(M.UI.modal)) : null")
def etat(pg): return pg.evaluate("() => JSON.parse(JSON.stringify(M.P().marche || null))")
def texte(pg): return pg.evaluate("() => { var e = document.querySelector('#voile'); return e ? e.innerText : ''; }")
def fermer(pg): pg.evaluate("() => M.fermer()"); pg.wait_for_timeout(80)
def apresmidi(pg):
    seq = pg.evaluate("() => M.code('moment:1')")
    pg.evaluate("() => { M.UI.modal = null; M.P().onglet = 'code'; M.render(); }")
    for s in seq: ev(pg, 'sym', {'s': s})
    pg.wait_for_timeout(300); pg.evaluate("() => { M.UI.modal = null; M.P().onglet = 'carte'; M.render(); }")
def neuf(b):
    pg = b.new_context(viewport={'width': 1180, 'height': 820}).new_page(); pg.set_default_timeout(8000)
    pg.on('console', lambda m: erreurs.append(m.text) if m.type == 'error' and 'net::' not in m.text and 'fonts' not in m.text and 'ERR_TUNNEL' not in m.text else None)
    pg.on('pageerror', lambda e: erreurs.append(f'PAGEERROR {e}'))
    pg.goto(URL)
    pg.click('[data-act=creer]'); pg.click('[data-act=crea-role][data-r=barde]'); pg.click('[data-act=crea-suite]'); pg.fill('#nom', 'Barde'); pg.click('[data-act=crea-fin]')
    pg.evaluate("() => { M.UI.ecran = 'reglages'; M.render(); }"); pg.click('[data-act=mode-test][data-i="3"]'); pg.click('#voile [data-act=confirmer-oui]')
    pg.evaluate("() => { M.S.talents = ['exiger']; M.sauver(); M.render(); }")
    pg.click('[data-act=nouvelle-enquete]'); pg.click('[data-act=lettre-suite]'); pg.click('[data-act=commencer]')
    return pg

with sync_playwright() as p:
    b = p.chromium.launch()
    print('— 1. Le Barde pressé')
    pg = neuf(b)
    ev(pg, 'lieu', {'id': 'boulangerie'}); ev(pg, 'parler', {'id': 'gaspard'})
    m = modal(pg)
    verifier(m and m['type'] == 'marche' and m['qui'] == 'maire', 'il touche Gaspard avant que le maire arrive : le maire d\'abord')
    fermer(pg); pg.wait_for_timeout(3300)
    m = modal(pg)
    verifier(m and m['type'] == 'marche' and m['qui'] == 'maire', 'fenêtre fermée sans la lire : le maire revient')
    pg.click('#voile [data-act=ma-debut]')
    ev(pg, 'lieu', {'id': 'place'}); ev(pg, 'parler', {'id': 'fortune'}); ev(pg, 'ma-fortune', {'k': '0'})
    s = etat(pg)
    verifier(s['f']['fini'] and s['or'] == 8 and s['papier'] == 4 and not s['lanterne'], '« Marché conclu ! » : 2 pièces, 4 bouquets en papier, pas de lanterne')
    fermer(pg)
    ev(pg, 'lieu', {'id': 'herboristerie'}); ev(pg, 'ma-vendeur', {'id': 'iris'}); ev(pg, 'ma-suite'); ev(pg, 'ma-choix', {'k': '3'})
    s = etat(pg)
    verifier(s['v']['iris']['fache'] and 'Du vol' in texte(pg) and s['papier'] == 0, 'Iris fâchée : elle ne vend rien (et le papier s\'est déchiré chez elle)')
    fermer(pg)
    ev(pg, 'lieu', {'id': 'herboristerie'})
    verifier(pg.locator('#voile [data-act=ma-vendeur]').count() == 0 and 'Je parle à mes fleurs' in texte(pg), 'elle est occupée, plus de bouton')
    fermer(pg)
    ev(pg, 'lieu', {'id': 'place'}); ev(pg, 'ma-vendeur', {'id': 'basile'})
    verifier((modal(pg) or {}).get('vue') == 'choix', 'chez Basile, plus de papier à déchirer : tout de suite ses 4 réponses')
    ev(pg, 'ma-choix', {'k': '0'}); ev(pg, 'ma-suite')
    verifier((modal(pg) or {}).get('n') == 4, 'au prix fort : 4 bouquets pour 8 pièces')
    ev(pg, 'ma-moins'); ev(pg, 'ma-moins'); ev(pg, 'ma-acheter')
    s = etat(pg)
    verifier(s['b'] == 2 and s['or'] == 4, 'il en prend 2 : il reste 4 pièces')
    fermer(pg)
    apresmidi(pg)
    verifier(pg.evaluate("() => M.pnjBulleCarte('basile') === '🌸' && !M.pnjBulleCarte('iris')"), 'l\'après-midi : Basile vend encore (bulle 🌸), Iris non')
    ev(pg, 'lieu', {'id': 'place'}); ev(pg, 'parler', {'id': 'basile'})
    verifier(pg.locator('#voile [data-act=ma-vendeur][data-id=basile]').count() == 1, 'dans la conversation de Basile : « Je voudrais des fleurs pour la fête. »')
    pg.screenshot(path=os.path.join(ICI, '..', 'test', 'e3-marche-basile-aprem.png'))
    ev(pg, 'ma-vendeur', {'id': 'basile'})
    verifier((modal(pg) or {}).get('vue') == 'quantite' and (modal(pg) or {}).get('n') == 2, 'au prix déjà obtenu, sans marchander')
    ev(pg, 'ma-acheter')
    s = etat(pg)
    verifier(s['b'] == 4 and s['or'] == 0, '4 bouquets en tout')
    fermer(pg)
    or0 = pg.evaluate("() => M.S.or")
    ev(pg, 'lieu', {'id': 'mairie'}); ev(pg, 'parler', {'id': 'grosbec'})
    verifier('enterrement' in texte(pg) and pg.evaluate("() => M.S.or") == or0, '4 bouquets : « une fête ou un enterrement ? », pas d\'or')
    verifier(pg.evaluate("() => !M.P().vus['marche:dix'] && !!M.P().vus['marche:rendu']"), 'la mission des 10 bouquets n\'est pas validée')
    pg.wait_for_timeout(1800); pg.screenshot(path=os.path.join(ICI, '..', 'test', 'e3-marche-maire-4.png'))
    ev(pg, 'ma-rendu')
    verifier((modal(pg) or {}).get('type') == 'conv', 'puis la conversation du maire')
    fermer(pg)
    ev(pg, 'lieu', {'id': 'place'}); ev(pg, 'parler', {'id': 'basile'})
    verifier(pg.locator('#voile [data-act=ma-vendeur]').count() == 0, 'après le maire : plus de fleurs à vendre')
    pg.context.close()

    print('— 2. Il montre qu\'il veut la lanterne')
    pg = neuf(b); pg.wait_for_timeout(3200); pg.click('#voile [data-act=ma-debut]')
    ev(pg, 'lieu', {'id': 'place'}); ev(pg, 'parler', {'id': 'fortune'}); ev(pg, 'ma-fortune', {'k': '2'})
    ev(pg, 'ma-fortune', {'k': '1'})
    verifier('10 pièces' in texte(pg) and etat(pg)['f']['sait'], '« Cette lanterne est magnifique ! » : il sait qu\'on la veut')
    fermer(pg)
    ev(pg, 'lieu', {'id': 'place'}); ev(pg, 'parler', {'id': 'fortune'})
    verifier((modal(pg) or {}).get('qui') == 'fortune' and '10 pièces' in texte(pg), 'fenêtre fermée en plein marchandage : on le retrouve à la même étape')
    ev(pg, 'ma-fortune', {'k': '1'})
    s = etat(pg)
    verifier(s['or'] == 6 and s['lanterne'] and 'deux pièces' in texte(pg), 'une pièce de plus ? Non : deux. 4 pièces en tout, avec la lanterne')
    fermer(pg)
    apresmidi(pg)
    ev(pg, 'lieu', {'id': 'herboristerie'})
    verifier(pg.locator('#voile [data-act=ma-vendeur][data-id=iris]').count() == 1, 'Iris, pas vue le matin : elle vend l\'après-midi')
    ev(pg, 'ma-vendeur', {'id': 'iris'}); ev(pg, 'ma-suite')
    verifier((modal(pg) or {}).get('vue') == 'choix', 'elle marchande alors (les 4 réponses)')
    ev(pg, 'ma-choix', {'k': '0'}); ev(pg, 'ma-suite'); ev(pg, 'ma-acheter')
    s = etat(pg)
    verifier(s['b'] == 6 and s['or'] == 0, '6 bouquets à 1 pièce')
    fermer(pg)
    # Basile, pas vu le matin non plus : même sans un sou, il marchande l'après-midi (son cadeau)
    ev(pg, 'lieu', {'id': 'place'}); ev(pg, 'parler', {'id': 'basile'})
    verifier(pg.locator('#voile [data-act=ma-vendeur][data-id=basile]').count() == 1, 'Basile, pas vu le matin : il vend l\'après-midi, même sans un sou')
    ev(pg, 'ma-vendeur', {'id': 'basile'}); ev(pg, 'ma-choix', {'k': '1'}); ev(pg, 'ma-suite'); ev(pg, 'ma-acheter')
    s = etat(pg)
    verifier(s['b'] == 9 and s['or'] == 0, 'il tient l\'échelle : 3 bouquets en cadeau, 9 en tout')
    pg.evaluate("() => { M.UI.modal = null; M.render(); }")
    or0 = pg.evaluate("() => M.S.or")
    ev(pg, 'lieu', {'id': 'mairie'}); ev(pg, 'parler', {'id': 'grosbec'})
    verifier('Il en manque un' in texte(pg) and pg.evaluate("() => M.S.or") == or0 + 10, '9 bouquets et la lanterne : 5 pièces, plus 5 pour la lanterne')
    pg.context.close()
    b.close()
print('\nErreurs JS :', len(erreurs))
for e in erreurs[:12]: print('  ', e[:300])
print('Vérifications ratées :', len(echecs))
for e in echecs: print('  ✗', e)
sys.exit(1 if erreurs or echecs else 0)
