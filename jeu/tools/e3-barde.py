    m = modal(pg)
    verifier(m and m['type'] == 'conv' and pg.locator('#voile [data-act=question]').count() == 4, 'Fortuné : maintenant, ses 4 questions')
    verifier(pg.locator('#voile [data-act=ma-plainte]').count() == 1, 'et on peut se plaindre des fleurs en papier')
