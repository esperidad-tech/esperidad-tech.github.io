    shot(pg, 'gaspard')
    toutes('gaspard', (0, 1, 2))
    verifier(pg.locator('#voile .bd-impatient').count() == 0, 'après trois questions : il écoute encore (plus de limite à deux)')
    poser(pg, 'gaspard', 3); pg.wait_for_timeout(300)
    verifier(pg.evaluate("() => [0, 1, 2, 3].every(i => M.P().vus['barde:gaspard:' + i] === 'ok')"), 'les quatre questions sont posées')
    verifier(pg.locator('#voile .bd-impatient').count() == 1 and 'pâte va retomber' in texte(pg), 'tout demandé : sa petite phrase, avec humour')
    verifier(pg.locator('#voile .bd-impatient .b-lire').count() == 1, 'et son 🔊')
    td = dedans(pg)
    verifier('plume de mes oies' in td and 'pas vu son visage' in td, 'Gaspard : une femme lui a demandé une plume, il n\'a pas vu son visage')
    shot(pg, 'gaspard-tout-demande')
    fermer(pg)
    ev(pg, 'lieu', {'id': 'boulangerie'})
    verifier('rien de plus à dire' in texte(pg) and pg.locator('#voile [data-act=parler][data-id=gaspard]').count() == 0, 'en revenant : « rien de plus à dire »')
    fermer(pg)
    # Fortuné, après le marchandage : un villageois comme les autres, et la plainte
