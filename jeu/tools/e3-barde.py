    verifier(pg.evaluate("() => M.pnjIci('herboristerie').length === 0"), 'Iris, qui répond le matin, reste cachée tant que Fortuné n\'a pas commencé')
    verifier(pg.locator('#carte-ici .ca-bulle-mq').count() == 1, 'une seule bulle sur la carte')
    shot(pg, 'carte-compteurs')
    # Fortuné
    ev(pg, 'lieu', {'id': 'place'})
    verifier('Basile' not in texte(pg), 'sur la place, Basile ne se voit pas encore')
