"""Enquête 3, étape 1 (Bible § 13.14) : le Barde, le matin et l'après-midi, sur une tablette (Playwright).
La lettre lue par le maire, l'écran des missions, le maire qui arrive, les compteurs, le marchandage de Fortuné (l'image de la carriole),
Basile et Iris, les deux questions par villageois et la phrase d'impatience, les occupés et leurs deux phrases, les écoutes aux portes,
puis l'après-midi : le maire compte les bouquets, la maison d'Odette (deux codes d'un coup), Mélusine et le code de l'Alchimiste.
L'enquête 3 est fermée aux joueurs : le robot l'ouvre comme un testeur, avec « #test » dans l'adresse.
   BRUMEVAL_DIST=<dossier construit> python3 tools/e3-barde.py [tendre] [iphone]
   tendre : le Barde a le talent « Tendre l'oreille » (la scène de Silas et Fortuné, les écoutes) ; sinon « Exige la vérité »."""
import sys, os, json
from playwright.sync_api import sync_playwright
ICI = os.path.dirname(os.path.abspath(__file__))
URL = 'file://' + os.path.join(os.path.abspath(os.environ.get('BRUMEVAL_DIST') or os.path.join(ICI, '..', 'dist')), 'index.html') + '#test'
TENDRE = 'tendre' in sys.argv
VUE = {'width': 390, 'height': 844} if 'iphone' in sys.argv else {'width': 1180, 'height': 820}
OUT = os.path.join(ICI, '..', 'test', 'e3-barde' + ('-tendre' if TENDRE else '') + ('-iphone' if 'iphone' in sys.argv else ''))
os.makedirs(OUT, exist_ok=True)
erreurs, echecs = [], []
n = [0]

def shot(pg, nom):
    n[0] += 1
    pg.wait_for_timeout(350)
    pg.screenshot(path=f'{OUT}/{n[0]:02d}-{nom}.png')

def verifier(cond, quoi):
    print('  ✓' if cond else '  ✗', quoi)
    if not cond: echecs.append(quoi)

def ev(pg, act, data=None):
    pg.evaluate(f"() => {{ M.A['{act}']({{dataset:{json.dumps(data or {})}, closest:function(){{ return null; }}}}); }}")
    pg.wait_for_timeout(120)

def modal(pg):
    return pg.evaluate("() => M.UI.modal ? JSON.parse(JSON.stringify(M.UI.modal)) : null")

def fermer(pg):
    pg.evaluate("() => { M.fermer(); }"); pg.wait_for_timeout(120)

def etat(pg):
    return pg.evaluate("() => JSON.parse(JSON.stringify(M.P().marche || null))")

def texte(pg, sel='#voile'):
    return pg.evaluate(f"() => {{ var e = document.querySelector('{sel}'); return e ? e.innerText : ''; }}")

def entrer(pg, cid):
    seq = pg.evaluate(f"() => M.code('{cid}')")
    pg.evaluate("() => { M.UI.modal = null; M.P().onglet = 'code'; M.render(); }")
    for s in seq: ev(pg, 'sym', {'s': s})
    pg.wait_for_timeout(400)

def poser(pg, pnj, i):
    ev(pg, 'question', {'p': pnj, 'i': str(i)})

