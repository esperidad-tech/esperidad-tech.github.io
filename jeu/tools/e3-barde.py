"""Enquête 3, étape 1 (Bible § 13.14) : le Barde, le matin et l'après-midi, sur une tablette (Playwright).
La lettre lue par le maire, l'écran des missions, le maire qui arrive, les compteurs, le marchandage de Fortuné (l'image de la carriole),
Basile et Iris, les deux questions par villageois et la phrase d'impatience, les occupés et leurs deux phrases, les écoutes aux portes,
puis l'après-midi : le maire compte les bouquets, la maison d'Odette (deux codes d'un coup), Mélusine et le code de l'Alchimiste.
L'enquête 3 est fermée aux joueurs : le robot l'ouvre comme un testeur, avec « #test » dans l'adresse.
   BRUMEVAL_DIST=<dossier construit> python3 tools/e3-barde.py [tendre] [iphone]
   tendre : le Barde a le talent « Tendre l'oreille » (la scène de Silas et Fortuné, les écoutes) ; sinon « Exige la vérité »."""
import sys, os, json
from playwright.sync_api import sync_playwright
ICI = os.path.dirname(os.path.abspath(__file__))
URL = 'file://' + os.path.join(os.path.abspath(os.environ.get('BRUMEVAL_DIST') or os.path.join(ICI, '..', 'dist')), 'index.html') + '#test'
TENDRE = 'tendre' in sys.argv
VUE = {'width': 390, 'height': 844} if 'iphone' in sys.argv else {'width': 1180, 'height': 820}
OUT = os.path.join(ICI, '..', 'test', 'e3-barde' + ('-tendre' if TENDRE else '') + ('-iphone' if 'iphone' in sys.argv else ''))
os.makedirs(OUT, exist_ok=True)
erreurs, echecs = [], []
n = [0]

def shot(pg, nom):
    n[0] += 1
    pg.wait_for_timeout(350)
    pg.screenshot(path=f'{OUT}/{n[0]:02d}-{nom}.png')

def verifier(cond, quoi):
    print('  ✓' if cond else '  ✗', quoi)
    if not cond: echecs.append(quoi)

def ev(pg, act, data=None):
    pg.evaluate(f"() => {{ M.A['{act}']({{dataset:{json.dumps(data or {})}, closest:function(){{ return null; }}}}); }}")
    pg.wait_for_timeout(120)

def modal(pg):
    return pg.evaluate("() => M.UI.modal ? JSON.parse(JSON.stringify(M.UI.modal)) : null")

def fermer(pg):
    pg.evaluate("() => { M.fermer(); }"); pg.wait_for_timeout(120)

def etat(pg):
    return pg.evaluate("() => JSON.parse(JSON.stringify(M.P().marche || null))")

def texte(pg, sel='#voile'):
    return pg.evaluate(f"() => {{ var e = document.querySelector('{sel}'); return e ? e.innerText : ''; }}")

def entrer(pg, cid):
    seq = pg.evaluate(f"() => M.code('{cid}')")
    pg.evaluate("() => { M.UI.modal = null; M.P().onglet = 'code'; M.render(); }")
    for s in seq: ev(pg, 'sym', {'s': s})
    pg.wait_for_timeout(400)

def poser(pg, pnj, i):
    ev(pg, 'question', {'p': pnj, 'i': str(i)})

with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_context(viewport=VUE).new_page()
    pg.set_default_timeout(8000)
    pg.on('console', lambda m: erreurs.append(m.text) if m.type == 'error' and 'net::' not in m.text and 'fonts' not in m.text and 'ERR_TUNNEL' not in m.text else None)
    pg.on('pageerror', lambda e: erreurs.append(f'PAGEERROR {e}'))
    pg.goto(URL)
    pg.click('[data-act=creer]'); pg.click('[data-act=crea-role][data-r=barde]'); pg.click('[data-act=crea-suite]'); pg.fill('#nom', 'Barde'); pg.click('[data-act=crea-fin]')
    pg.evaluate("() => { M.UI.ecran = 'reglages'; M.render(); }"); pg.click('[data-act=mode-test][data-i="3"]'); pg.click('#voile [data-act=confirmer-oui]')
    pg.evaluate("(t) => { M.S.talents = [t]; M.sauver(); M.render(); }", 'tendre' if TENDRE else 'exiger')
    verifier(pg.locator('[data-act=nouvelle-enquete]').count() == 1, 'avec #test, le village propose l\'enquête 3')
    pg.click('[data-act=nouvelle-enquete]')
    print('— L\'ouverture')
    verifier('Mon cher Monsieur le maire' in texte(pg, '#app') and 'grande fête cette nuit' in texte(pg, '#app'), 'la lettre d\'Odette, puis ce qu\'annonce le maire')
    shot(pg, 'lettre')
    pg.click('[data-act=lettre-suite]')
    verifier(pg.locator('.b-mm-ligne').count() == 4 and pg.locator('.b-mm-ligne.moi').count() == 1, 'l\'écran des missions : quatre lignes, la sienne en couleur')
    verifier(pg.locator('.b-mm-ligne .b-lire').count() == 4, 'un 🔊 par mission')
    shot(pg, 'missions')
    pg.click('[data-act=commencer]')
    verifier(pg.evaluate("() => M.P().etape === 'jeu' && !M.P().marche"), 'l\'enquête commence, le maire n\'est pas encore là')
    verifier(pg.evaluate("() => Object.keys(M.barde.mimiques()).length >= 6"), 'les six signes des menteurs sont épinglés d\'office')
    pg.evaluate("() => { M.P().onglet = 'carte'; M.render(); }")
    pg.wait_for_timeout(3200)
    print('— Le marché aux fleurs')
    m = modal(pg)
    verifier(m and m['type'] == 'marche' and m['qui'] == 'maire', 'le maire arrive tout seul, 2 à 3 secondes après')
    shot(pg, 'maire-arrive')
    pg.click('#voile [data-act=ma-debut]')
    s = etat(pg)
    verifier(s and s['or'] == 10 and s['b'] == 0, '10 pièces, 0 bouquet')
    verifier('10' in texte(pg, '#ma-compteurs') and 'sur 10' in texte(pg, '#ma-compteurs'), 'les deux compteurs sur la carte')
    verifier(pg.evaluate("() => M.pnjCacheCarte('iris') && M.pnjCacheCarte('basile') && M.pnjBulleCarte('fortune') === '🌸'"), 'Iris et Basile cachés, la bulle 🌸 sur Fortuné')
    verifier(pg.locator('#carte-ici .ca-bulle-mq').count() == 1, 'une seule bulle sur la carte')
    shot(pg, 'carte-compteurs')
    # Fortuné
    ev(pg, 'lieu', {'id': 'place'})
    verifier('Basile' not in texte(pg), 'sur la place, Basile ne se voit pas encore')
    ev(pg, 'parler', {'id': 'fortune'})
    m = modal(pg)
    if TENDRE:
        verifier(m and m['type'] == 'porte', 'avec Tendre l\'oreille : d\'abord la scène de Silas et Fortuné')
        shot(pg, 'ecoute-silas-fortune')
        for _ in range(12):
            if (modal(pg) or {}).get('type') != 'porte': break
            ev(pg, 'bd-porte-fin')
        m = modal(pg)
    verifier(m and m['type'] == 'marche' and m['qui'] == 'fortune', 'puis le marchandage de Fortuné')
    verifier('4 bouquets pour 2 pièces' in texte(pg), 'étape 1 : son offre')
    verifier(pg.locator('#voile .ma-ligne .b-lire').count() == 4, 'un 🔊 par réponse')
    shot(pg, 'fortune-1')
    ev(pg, 'ma-fortune', {'k': '1'})
    verifier('moitié prix, mon ami' in texte(pg) and 'dans ma carriole' in texte(pg), 'sa réplique, puis la relance commune')
    verifier(pg.locator('#voile .sf-carriole').count() == 1, 'étape 2 : l\'image de la carriole')
    verifier('lanterne' not in pg.evaluate("() => document.querySelector('#voile .ma-dit').innerText").lower(), 'aucun texte ne décrit la lanterne')
    shot(pg, 'fortune-2-carriole')
    ev(pg, 'ma-fortune', {'k': '2'})
    verifier('ne fanent jamais' in texte(pg) and pg.locator('#voile .ma-ligne').count() == 3, 'une réponse qui fait rester disparaît')
    ev(pg, 'ma-fortune', {'k': '0'})
    verifier('Une vieille lanterne' in texte(pg), 'étape 3')
    shot(pg, 'fortune-3')
    ev(pg, 'ma-fortune', {'k': '0'})
    s = etat(pg)
    verifier(s['f']['fini'] and s['or'] == 8 and s['papier'] == 4 and s['lanterne'], 'marché conclu : 2 pièces, 4 bouquets en papier, la lanterne')
    shot(pg, 'fortune-fin')
    fermer(pg)
    verifier(pg.evaluate("() => !M.pnjCacheCarte('iris') && !M.pnjCacheCarte('basile')"), 'Iris et Basile sont apparus sur la carte')
    pg.evaluate("() => { M.P().onglet = 'carte'; M.render(); }")
    shot(pg, 'carte-apres-fortune')
    # Basile : il tient l'échelle, 3 bouquets en cadeau ; il n'achète rien de plus
    ev(pg, 'lieu', {'id': 'place'})
    verifier(pg.locator('#voile [data-act=ma-vendeur][data-id=basile]').count() == 1, 'sur la place, Basile vend des fleurs')
    shot(pg, 'place-basile-vend')
    ev(pg, 'ma-vendeur', {'id': 'basile'})
    verifier('fleurs en papier' in texte(pg) and etat(pg)['papier'] == 0, 'chez le premier vrai fleuriste, les bouquets en papier se déchirent')
    shot(pg, 'papier-dechire')
    ev(pg, 'ma-suite')
    verifier(pg.locator('#voile .ma-ligne').count() == 4, 'Basile : 4 façons de demander')
    shot(pg, 'basile-choix')
    ev(pg, 'ma-choix', {'k': '1'})
    verifier('cadeau' in texte(pg) and etat(pg)['b'] == 3, 'il tient l\'échelle : 3 bouquets en cadeau')
    ev(pg, 'ma-suite')
    shot(pg, 'basile-quantite')
    for _ in range(6): ev(pg, 'ma-moins')
    ev(pg, 'ma-acheter')
    s = etat(pg)
    verifier(s['or'] == 8 and s['b'] == 3 and s['v']['basile']['fait'], 'il garde ses 8 pièces')
    ev(pg, 'lieu', {'id': 'place'})
    t1 = texte(pg)
    verifier('lampions' in t1 and pg.locator('#voile [data-act=ma-vendeur]').count() == 0, 'après la vente, Basile est occupé : sa première petite phrase')
    fermer(pg); ev(pg, 'lieu', {'id': 'place'})
    verifier('Attention en dessous' in texte(pg), 'en revenant : sa deuxième petite phrase')
    shot(pg, 'place-occupes')
    fermer(pg)
    # Iris : il sent les fleurs, 1 pièce le bouquet, 8 bouquets
    ev(pg, 'lieu', {'id': 'herboristerie'})
    shot(pg, 'iris-vend')
    ev(pg, 'ma-vendeur', {'id': 'iris'})
    ev(pg, 'ma-choix', {'k': '0'})
    verifier('1 pièce le bouquet' in texte(pg), 'Iris : il sent les fleurs, 1 pièce le bouquet')
    ev(pg, 'ma-suite')
    verifier((modal(pg) or {}).get('n') == 8, 'elle propose d\'abord tout ce qu\'il peut payer : 8')
    shot(pg, 'iris-quantite')
    ev(pg, 'ma-acheter')
    s = etat(pg)
    verifier(s['or'] == 0 and s['b'] == 11, 'au mieux : 11 bouquets, plus une pièce')
    shot(pg, 'iris-merci')
    fermer(pg)
    pg.evaluate("() => { M.P().onglet = 'carte'; M.render(); }")
    verifier('11' in texte(pg, '#ma-compteurs') and '🏮' in texte(pg, '#ma-compteurs'), 'les compteurs : 0 pièce, 11 bouquets, la lanterne')
    shot(pg, 'carte-11-bouquets')

    print('— Les villageois du matin')
    ev(pg, 'lieu', {'id': 'boulangerie'}); ev(pg, 'parler', {'id': 'gaspard'})
    verifier(pg.locator('#voile [data-act=question]').count() == 4, 'Gaspard : 4 questions')
    shot(pg, 'gaspard')
    poser(pg, 'gaspard', 0)
    verifier(pg.locator('#voile .bd-impatient').count() == 0, 'après une question : il écoute encore')
    poser(pg, 'gaspard', 1)
    verifier(pg.locator('#voile .bd-impatient').count() == 1 and 'pâte va retomber' in texte(pg), 'après deux questions : sa phrase d\'impatience')
    verifier(pg.locator('#voile [data-act=question].bd-a-poser').count() == 0, 'les deux autres questions ont disparu')
    shot(pg, 'gaspard-impatient')
    poser(pg, 'gaspard', 2)
    verifier(pg.evaluate("() => !M.P().vus['barde:gaspard:2']"), 'une troisième question ne passe pas')
    fermer(pg)
    ev(pg, 'lieu', {'id': 'boulangerie'}); ev(pg, 'parler', {'id': 'gaspard'}); pg.wait_for_timeout(2600)   # (sa phrase s'écrit lettre après lettre)
    verifier('pâte va retomber' in texte(pg) and pg.locator('#voile [data-act=question]').count() == 0, 'en revenant : « Encore toi ? », avec sa phrase à lui')
    shot(pg, 'gaspard-encore')
    fermer(pg)
    # Fortuné, après le marchandage : un villageois comme les autres, et la plainte
    ev(pg, 'lieu', {'id': 'place'}); ev(pg, 'parler', {'id': 'fortune'})
    m = modal(pg)
    verifier(m and m['type'] == 'conv' and pg.locator('#voile [data-act=question]').count() == 4, 'Fortuné : maintenant, ses 4 questions')
    verifier(pg.locator('#voile [data-act=ma-plainte]').count() == 1, 'et on peut se plaindre des fleurs en papier')
    ev(pg, 'ma-plainte'); pg.wait_for_timeout(3000)
    verifier('ni reprise ni échangée' in texte(pg), '« Marchandise vendue, ni reprise ni échangée ! »')
    shot(pg, 'fortune-plainte')
    fermer(pg)
    # Victor : un code pour le Sage
    ev(pg, 'lieu', {'id': 'poste'}); ev(pg, 'parler', {'id': 'victor'})
    verifier(pg.locator('#voile [data-act=question]').count() == (5 if False else 4), 'Victor : 4 questions (la 5e attend l\'écoute de la mairie)')
    poser(pg, 'victor', 1)
    m = modal(pg)
    verifier(m and m['type'] == 'decouverte' and m.get('code') == 'info:poste', 'Victor donne le code « La lettre n\'est pas passée par la poste »')
    shot(pg, 'victor-code')
    ev(pg, 'parler', {'id': 'victor'}); fermer(pg)
    # Tim : il ment, démasqué → le code du capuchon
    ev(pg, 'lieu', {'id': 'clocher'})
    verifier('VA ME CHERCHER L\'ALCHIMISTE' in texte(pg), 'au clocher : Anselme, occupé, fait appeler l\'Alchimiste (sa tisane de mélisse : Bible §13.28), et Tim')
    shot(pg, 'clocher-matin')
    ev(pg, 'parler', {'id': 'tim'}); poser(pg, 'tim', 0)
    verifier(pg.locator('#voile [data-act=bd-ment]').count() == 1, 'le 🤥 sous la dernière réponse')
    ev(pg, 'bd-ment', {'p': 'tim', 'i': '0'})
    m = modal(pg)
    verifier(m and m['type'] == 'decouverte' and m.get('code') == 'info:capuchon', 'Tim démasqué donne le code « Le capuchon vers le clocher »')
    shot(pg, 'tim-capuchon')
    fermer(pg)
    # les occupés du matin
    ev(pg, 'lieu', {'id': 'atelier'})
    verifier('banderole de Pompon' in texte(pg), 'Mélusine, occupée : sa première phrase')
    fermer(pg); ev(pg, 'lieu', {'id': 'atelier'})
    verifier('Attention à mes épingles' in texte(pg), 'puis la deuxième')
    fermer(pg)
    ev(pg, 'lieu', {'id': 'mairie'})
    verifier('Mes fleurs d\'abord' in texte(pg), 'le maire, occupé le matin')
    shot(pg, 'mairie-matin')
    if TENDRE:
        verifier(pg.locator('#voile [data-act=bd-porte]').count() == 1, 'Tendre l\'oreille : écouter aux portes de la mairie')
        ev(pg, 'bd-porte', {'l': 'mairie'})
        shot(pg, 'ecoute-mairie')
        for _ in range(8):
            if (modal(pg) or {}).get('type') != 'porte': break
            ev(pg, 'bd-porte-fin')
        fermer(pg)
        ev(pg, 'lieu', {'id': 'poste'}); ev(pg, 'parler', {'id': 'victor'})
        verifier(pg.locator('#voile [data-act=question].bd-a-poser').count() == 4 and 'vous taire' in texte(pg), 'l\'écoute ouvre une question de plus chez Victor')
        poser(pg, 'victor', 4); poser(pg, 'victor', 0)
        verifier(pg.evaluate("() => M.P().visites.victor.n === 2") and pg.locator('#voile .bd-impatient').count() == 1, 'la question venue de l\'écoute ne compte pas dans ses deux questions')
        shot(pg, 'victor-nouveau')
        fermer(pg)
        # une maison où il y a quelque chose à écouter : la feuille, avec « Frapper » et « Écouter aux portes »
        ev(pg, 'maison', {'id': 'L1'})
        verifier(pg.locator('#voile [data-act=bd-porte]').count() == 1 and pg.locator('#voile [data-act=frapper]').count() == 1, 'rue des Lanternes : frapper, ou écouter')
        shot(pg, 'maison-voisin')
        fermer(pg)
    ev(pg, 'frapper', {'id': 'L1'})
    m = modal(pg)
    verifier(m and m['type'] == 'conv' and m['id'] == 'levoisin', 'le voisin d\'Odette ouvre sa porte')
    shot(pg, 'voisin')
    fermer(pg)
    ev(pg, 'frapper', {'id': 'L2'})
    verifier('chez sa sœur' in texte(pg), 'le matin, chez Odette : personne')
    fermer(pg)

    print('— L\'après-midi')
    entrer(pg, 'moment:1')
    verifier(pg.evaluate("() => M.momentId() === 'apresmidi'"), 'le code de l\'après-midi')
    pg.evaluate("() => { M.UI.modal = null; M.P().onglet = 'carte'; M.render(); }")
    verifier(pg.evaluate("() => M.pnjBulleCarte('grosbec') === '💐'"), 'la bulle 💐 sur le maire')
    shot(pg, 'carte-apresmidi')
    or0 = pg.evaluate("() => M.S.or")
    ev(pg, 'lieu', {'id': 'mairie'}); ev(pg, 'parler', {'id': 'grosbec'})
    m = modal(pg)
    verifier(m and m['type'] == 'marche' and m['qui'] == 'retour', 'le maire compte les bouquets')
