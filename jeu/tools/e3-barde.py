    m = modal(pg)
    if TENDRE:
        verifier(m and m['type'] == 'porte', 'avec Tendre l\'oreille : d\'abord la scène de Silas et Fortuné')
        shot(pg, 'ecoute-silas-fortune')
        for _ in range(12):
            if (modal(pg) or {}).get('type') != 'porte': break
            ev(pg, 'bd-porte-fin')
        m = modal(pg)
    verifier(m and m['type'] == 'marche' and m['qui'] == 'fortune', 'puis le marchandage de Fortuné')
    verifier('4 bouquets pour 2 pièces' in texte(pg), 'étape 1 : son offre')
