    # ---------- (12 novembre au soir) les dialogues refaits : trois questions communes, une sur le métier, plus de limite à deux ----------
    def toutes(pnj, ids):
        for i in ids: poser(pg, pnj, i)
        pg.wait_for_timeout(150)
    def mission(i):
        return pg.evaluate("(i) => { M.render(); return !!(M.P().mission && M.P().mission.faits[i]); }", i)
    def demasquer(pnj, i):
        poser(pg, pnj, i); ev(pg, 'bd-ment', {'p': pnj, 'i': str(i)})
    def dedans(pg):   # tout le texte de la fenêtre, y compris les réponses repliées (innerText ne les voit pas)
        pg.wait_for_timeout(2600)
        return pg.evaluate("() => { var e = document.querySelector('#voile'); return e ? e.textContent : ''; }")
    COMMUNES = ['Que pensez-vous de la lettre', 'Vous connaissez bien Odette', 'quelque chose de bizarre, cette nuit']

    print('— Les villageois du matin')
    ev(pg, 'lieu', {'id': 'boulangerie'}); ev(pg, 'parler', {'id': 'gaspard'})
