    verifier(pg.locator('#voile [data-act=parler][data-id=iris]').count() == 1 and pg.locator('#voile [data-act=ma-vendeur][data-id=iris]').count() == 1, 'à l\'herboristerie : parler à Iris, ou lui acheter des fleurs')
