    shot(pg, 'victor-code')
    ev(pg, 'parler', {'id': 'victor'})
    verifier('Comment savoir si c\'est vraiment Odette' in texte(pg), 'puis son idée arrive : comment savoir si Odette l\'a écrite ?')
    poser(pg, 'victor', 4); pg.wait_for_timeout(2600)
    verifier('comparer avec quelque chose' in texte(pg), 'Victor : il faudrait comparer avec un papier à elle, chez elle')
