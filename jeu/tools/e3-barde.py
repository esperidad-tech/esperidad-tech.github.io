    # Mélusine : sans le code, 4 questions ; avec, l'aveu
    ev(pg, 'lieu', {'id': 'atelier'}); ev(pg, 'parler', {'id': 'melusine'})
    verifier(pg.locator('#voile [data-act=question]').count() == 4 and 'votre écriture' not in texte(pg), 'Mélusine : 4 questions, pas encore celle de l\'écriture')
