"""La pause des mini-jeux : #mj-plein (Pisteur, poursuite) et le chaudron de l'atelier (Alchimiste)."""
import os, sys, json
from playwright.sync_api import sync_playwright
D = os.path.abspath(os.environ.get('BRUMEVAL_DIST') or os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'dist'))
URL = 'file://' + os.path.join(D, 'index.html')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'test', 'pause')
os.makedirs(OUT, exist_ok=True)
erreurs, echecs = [], []
def ok(c, q):
    print(('  ✓ ' if c else '  ✗ ') + q)
    if not c: echecs.append(q)
def creer(b, role, dsf=1):
    pg = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=dsf).new_page()
    pg.set_default_timeout(8000)
    pg.on('console', lambda m: erreurs.append(f'[{role}] {m.text}') if m.type == 'error' and 'ERR_TUNNEL' not in m.text and 'fonts' not in m.text and 'net::' not in m.text else None)
    pg.on('pageerror', lambda e: erreurs.append(f'[{role}] PAGEERROR {e}'))
    pg.goto(URL)
    pg.click('[data-act=creer]'); pg.click(f'[data-act=crea-role][data-r={role}]'); pg.click('[data-act=crea-suite]'); pg.fill('#nom', role.capitalize()); pg.click('[data-act=crea-fin]')
    pg.evaluate("() => { M.UI.ecran = 'reglages'; M.render(); }"); pg.click('[data-act=mode-test][data-i="2"]'); pg.click('#voile [data-act=confirmer-oui]')
    pg.click('[data-act=nouvelle-enquete]'); pg.click('[data-act=commencer]')
    pg.wait_for_timeout(300)
    # le talent forcé du niveau 2 : on le prend tout de suite (sinon il bloque)
    pg.evaluate("""() => { try{ var t = M.tutoTalentForce && M.tutoTalentForce(); if(t){ var id = DONNEES.TALENTS_PAR_ROLE[M.role()][2][0]; M.A.talent({dataset:{id:id}}); } }catch(e){} M.UI.modal = null; M.render(); }""")
    return pg
def mjT(pg): return pg.evaluate('() => MJT.performance.now()')

with sync_playwright() as p:
    b = p.chromium.launch()
    # ---------- 1. Pisteur : une poursuite dans #mj-plein ----------
    print('— Pisteur, poursuite')
    pg = creer(b, 'pisteur', 2)
    pg.evaluate("() => { var P = M.P(); P.onglet = 'carte'; M.UI.modal = null; M.render(); }")
    pg.wait_for_timeout(400)
    pg.evaluate("() => { window.__fin = null; M.lancerMJ('poursuite', 2, null, {titre:'Rattraper le voleur'}, function(r){ window.__fin = r; }); }")
    pg.wait_for_timeout(300)
    pg.click('#voile [data-act=mj-go]')
    pg.wait_for_timeout(300)
    if pg.locator('#voile [data-act=mj-potion]').count(): pg.click('#voile [data-act=mj-potion][data-id=""]')
    if pg.locator('#voile [data-act=mj-auto]').count(): pg.click('#voile [data-act=mj-auto][data-oui=""]')
    pg.wait_for_timeout(300)
    ok(pg.locator('#mj-plein .mj-btn-pause').count() == 1, 'le bouton ⏸️ est dans l\'en-tête')
    pg.click('#mj-plein .mj-go'); pg.wait_for_timeout(1500)
    pg.screenshot(path=f'{OUT}/01-poursuite.png')
    t0 = mjT(pg); pg.wait_for_timeout(500); t1 = mjT(pg)
    ok(t1 - t0 > 300, f'le temps du mini-jeu avance ({round(t1 - t0)} ms)')
    etat0 = pg.evaluate('() => MJT._etat()'); print('   ', etat0)
    pg.click('#mj-plein .mj-btn-pause'); pg.wait_for_timeout(400)
    ok(pg.evaluate('() => MJT.enPause() && !!M.mjPause && M.mjPause.hote === "plein"'), 'en pause')
    ok(pg.evaluate('() => document.getElementById("mj-plein").classList.contains("mj-cache")'), '#mj-plein caché')
    ok(pg.locator('#mj-rappel:not([hidden])').count() == 1, 'le rappel est là')
    ok(not pg.evaluate('() => document.body.classList.contains("b-bloque")'), 'la page n\'est plus bloquée')
    t0 = mjT(pg); pg.wait_for_timeout(1500); t1 = mjT(pg)
    ok(abs(t1 - t0) < 1, f'le temps du mini-jeu est figé ({round(t1 - t0)} ms)')
    pg.screenshot(path=f'{OUT}/02-pause-carte.png')
    # un lieu de la carte : la bulle s'ouvre, mais « Explorer » attend
    lieu = pg.evaluate("() => { var e = document.querySelector('#carte-ici [data-act=lieu]'); return e ? e.dataset.id : null; }")
    print('    lieu', lieu)
    if lieu:
        pg.evaluate(f"() => document.querySelector('#carte-ici [data-act=lieu][data-id={lieu}]').dispatchEvent(new MouseEvent('click', {{bubbles:true}}))")
        pg.wait_for_timeout(700)
        pg.screenshot(path=f'{OUT}/03-bulle.png')
        btn = pg.evaluate("() => { var b = document.querySelector('#voile .b-bulle [data-act]:not([data-act=fermer]):not([data-act=lire])'); return b ? b.dataset.act : null; }")
        print('    action de la bulle :', btn)
        if btn and btn not in ('lieu', 'maison', 'onglet'):
            pg.click(f'#voile .b-bulle [data-act="{btn}"]'); pg.wait_for_timeout(500)
            ok(pg.locator('#voile .b-mj-pause').count() == 1, f'« {btn} » pendant la pause : la fenêtre « Un mini-jeu est en pause »')
            pg.screenshot(path=f'{OUT}/04-fenetre-pause.png')
            pg.click('#voile .b-mj-pause [data-act=fermer]'); pg.wait_for_timeout(300)
    # l'onglet Code : on tape le code du moment suivant → il attend
    pg.click('[data-act=onglet][data-o=code]'); pg.wait_for_timeout(400)
    syms = pg.evaluate("() => M.code('moment:1')")
    for s in syms:
        pg.click(f'[data-act=sym][data-s="{s}"]'); pg.wait_for_timeout(120)
    pg.wait_for_timeout(600)
    ok(pg.locator('#voile .b-mj-pause').count() == 1, 'le code du moment suivant attend la fin du mini-jeu')
    ok(pg.evaluate('() => M.P().moment') == 0, 'le moment n\'a pas changé')
    pg.screenshot(path=f'{OUT}/05-code-moment.png')
    pg.click('#voile .b-mj-pause [data-act=fermer]'); pg.wait_for_timeout(300)
    # un autre mini-jeu : refusé
    pg.evaluate("() => M.lancerMJ('tir', 2, null, {titre:'Autre'}, function(){})"); pg.wait_for_timeout(300)
    ok(pg.locator('#voile .b-mj-pause').count() == 1, 'pas d\'autre mini-jeu pendant la pause')
    # Reprendre (depuis la fenêtre)
    pg.click('#voile [data-act=mj-reprendre]'); pg.wait_for_timeout(250)
    ok(pg.evaluate('() => M.P().onglet') == 'carte', 'de retour sur l\'onglet du mini-jeu (la carte)')
    ok(pg.locator('#mj-plein .mj-decompte').count() == 1, '« 3, 2, 1 »')
    ok(pg.locator('#mj-rappel:not([hidden])').count() == 0, 'le rappel est parti')
    pg.screenshot(path=f'{OUT}/06-decompte.png')
    t0 = mjT(pg); pg.wait_for_timeout(800); t1 = mjT(pg)
    ok(abs(t1 - t0) < 1, 'encore figé pendant « 3, 2, 1 »')
    pg.wait_for_timeout(1400)
    ok(not pg.evaluate('() => MJT.enPause()'), 'ça repart')
    t0 = mjT(pg); pg.wait_for_timeout(500); t1 = mjT(pg)
    ok(t1 - t0 > 300, f'le temps avance de nouveau ({round(t1 - t0)} ms)')
    ok(pg.evaluate('() => document.body.classList.contains("b-bloque")'), 'la page est de nouveau bloquée derrière le mini-jeu')
    # on laisse perdre : le résultat, puis Continuer
    try:
        pg.wait_for_selector('#mj-plein .mj-resultat', timeout=60000)
        pg.screenshot(path=f'{OUT}/07-resultat.png')
        pg.click('#mj-plein .mj-continuer'); pg.wait_for_timeout(400)
        ok(pg.evaluate('() => !!window.__fin'), 'la fin du mini-jeu arrive au moteur : ' + json.dumps(pg.evaluate('() => window.__fin && {reussi:window.__fin.reussi, essais:window.__fin.essais}')))
    except Exception as e:
        ok(False, 'pas de résultat : ' + str(e)[:80])
    ok(pg.evaluate('() => !M.mjPause && !MJT.enPause()'), 'plus de pause après la fin')
    # une 2e fois : pause pendant l'accueil (pas de 3, 2, 1)
    pg.evaluate("() => { M.lancerMJ('tir', 2, null, {titre:'Viser', sansIntro:true}, function(r){ window.__fin2 = r; }); }"); pg.wait_for_timeout(300)
    if pg.locator('#voile [data-act=mj-potion]').count(): pg.click('#voile [data-act=mj-potion][data-id=""]')
    if pg.locator('#voile [data-act=mj-auto]').count(): pg.click('#voile [data-act=mj-auto][data-oui=""]')
    pg.wait_for_timeout(300)
    pg.click('#mj-plein .mj-btn-pause'); pg.wait_for_timeout(300)
    pg.click('#mj-rappel .mj-rp-go'); pg.wait_for_timeout(200)
    ok(pg.locator('#mj-plein .mj-decompte').count() == 0 and not pg.evaluate('() => MJT.enPause()'), 'sur l\'accueil : ça reprend tout de suite')
    pg.evaluate("() => { var pl = document.getElementById('mj-plein'); }")
    pg.close()

    # ---------- 2. Alchimiste : le chaudron de l'atelier ----------
    print('— Alchimiste, chaudron de l\'atelier')
    pg = creer(b, 'alchimiste', 2)
    rid = pg.evaluate("""() => { var r = M.recettesConnues().filter(function(x){ return !DONNEES.RECETTES[x].secrete; })[0];
      var S = M.S, P = M.P(); P.onglet = 'role'; S.fioles = Math.max(S.fioles, 2); P.actions = 2;
      M.UI.modal = null; M.render(); return r; }""")
    pg.wait_for_timeout(800)
    # ranger les ingrédients de la recette dans un meuble
    pg.evaluate("""(rid) => { var S = M.S, R = DONNEES.RECETTES[rid], o = S.atelier.objets.filter(function(x){ return x.cases && x.cases.length; })[0];
      R.ingr.forEach(function(x){ o.cases[0].i[x[0]] = (o.cases[0].i[x[0]] || 0) + x[1]; }); M.sauver(); M.render(); }""", rid)
    pg.wait_for_timeout(900)
    print('    recette', rid)
    # ouvrir le chaudron (l'objet de la pièce)
    ch = pg.locator('#atelier-ici [data-obj=ch]')
    print('    chaudron dans la pièce :', ch.count())
    if ch.count(): ch.first.click(); pg.wait_for_timeout(700)
    go = pg.locator(f'#atelier-ici .at-ch-go[data-r={rid}]')
    print('    bouton préparer :', go.count())
    pg.screenshot(path=f'{OUT}/10-atelier-chaudron.png')
    if go.count():
        go.first.click(); pg.wait_for_timeout(700)
        ok(pg.locator('#atelier-ici .at-mj .mj-btn-pause').count() == 1, 'le chaudron a son ⏸️')
        if pg.locator('#atelier-ici .at-mj .mj-go').count(): pg.click('#atelier-ici .at-mj .mj-go'); pg.wait_for_timeout(1200)
        pg.screenshot(path=f'{OUT}/11-chaudron-jeu.png')
        # changer d'onglet pendant le chaudron : il se met en pause (avant : abandonné)
        pg.click('[data-act=onglet][data-o=carte]'); pg.wait_for_timeout(600)
        ok(pg.evaluate('() => !!M.mjPause && M.mjPause.hote === "atelier" && MJT.enPause()'), 'changer d\'onglet met le chaudron en pause')
        ok(pg.evaluate('() => document.getElementById("mj-parking").childElementCount') > 0, 'l\'atelier attend de côté')
        ok(pg.locator('#mj-rappel:not([hidden])').count() == 1, 'le rappel est là')
        pg.screenshot(path=f'{OUT}/12-chaudron-pause-carte.png')
        # retour à l'atelier sans reprendre : l'atelier revient, le chaudron reste caché
        pg.click('[data-act=onglet][data-o=role]'); pg.wait_for_timeout(600)
        ok(pg.evaluate('() => document.getElementById("mj-parking").childElementCount') == 0, 'l\'atelier est revenu à sa place')
        ok(pg.evaluate('() => !!document.querySelector("#atelier-ici .at-mj.mj-cache")'), 'le chaudron, toujours en pause, reste caché')
        pg.screenshot(path=f'{OUT}/13-atelier-pause.png')
        pg.click('[data-act=onglet][data-o=code]'); pg.wait_for_timeout(500)
        pg.click('#mj-rappel .mj-rp-go'); pg.wait_for_timeout(300)
        ok(pg.evaluate('() => M.P().onglet') == 'role', 'Reprendre ramène à l\'atelier')
        ok(pg.locator('#atelier-ici .at-mj:not(.mj-cache) .mj-decompte').count() == 1, '« 3, 2, 1 » sur le chaudron')
        pg.screenshot(path=f'{OUT}/14-chaudron-reprise.png')
        pg.wait_for_timeout(2200)
        ok(not pg.evaluate('() => MJT.enPause()'), 'le chaudron repart')
        # le bouton ⏸️ du chaudron
        pg.click('#atelier-ici .at-mj .mj-btn-pause'); pg.wait_for_timeout(400)
        ok(pg.evaluate('() => !!M.mjPause && MJT.enPause()'), '⏸️ du chaudron : en pause')
        pg.click('#mj-rappel .mj-rp-go'); pg.wait_for_timeout(2400)
        ok(not pg.evaluate('() => MJT.enPause() || !!M.mjPause'), 'et ça repart')
    else:
        ok(False, 'pas de bouton pour préparer la potion')
    b.close()
print('ÉCHECS', echecs)
print('ERREURS', erreurs[:10])
