import os
from playwright.sync_api import sync_playwright
ICI = os.path.dirname(os.path.abspath(__file__))
URL = 'file://' + os.path.join(os.path.abspath(os.environ.get('BRUMEVAL_DIST') or os.path.join(ICI, '..', 'dist')), 'index.html')
OUT = os.path.join(ICI, '..', 'test', 'ecrans'); os.makedirs(OUT, exist_ok=True)
with sync_playwright() as p:
    b = p.chromium.launch()
    for (W, H, tag) in [(390, 844, 'tel'), (1280, 800, 'paysage')]:
        pg = b.new_context(viewport={'width': W, 'height': H}).new_page(); pg.set_default_timeout(6000)
        errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.goto(URL); pg.wait_for_timeout(300); pg.screenshot(path=f'{OUT}/{tag}-1-accueil.png')
        pg.click('[data-act=creer]'); pg.click('[data-act=crea-role][data-r=barde]'); pg.screenshot(path=f'{OUT}/{tag}-2-roles.png')
        pg.click('[data-act=crea-suite]'); pg.click('[data-act=crea-opt][data-k=sexe][data-v=m]'); pg.click('[data-act=crea-opt][data-k=age][data-v=age]')
        pg.screenshot(path=f'{OUT}/{tag}-3-apparence.png')
        pg.click('[data-act=crea-suite]'); pg.fill('#nom', 'Romain'); pg.click('[data-act=crea-fin]')
        pg.click('[data-act=ecran][data-e=reglages]'); pg.click('[data-act=mode-test][data-i="2"]'); pg.click('#voile [data-act=confirmer-oui]')
        pg.screenshot(path=f'{OUT}/{tag}-4-hub.png')
        pg.click('[data-act=ecran][data-e=boutique]'); pg.screenshot(path=f'{OUT}/{tag}-5-boutique.png')
        pg.click('[data-act=acheter][data-id=clochette]'); pg.wait_for_timeout(200); pg.screenshot(path=f'{OUT}/{tag}-6-achat.png')
        pg.click('#voile .b-fermer'); pg.click('[data-act=ecran][data-e=accueil]')
        pg.click('[data-act=nouvelle-enquete]'); pg.wait_for_timeout(200); pg.screenshot(path=f'{OUT}/{tag}-7-lettre.png')
        pg.click('[data-act=commencer]')
        pg.evaluate("() => { MJ.__vrai = true; }")
        pg.click('[data-act=onglet][data-o=carte]'); pg.click('#carte-ici g.ca-lieu[data-lieu=atelier] .ca-etiq-lieu'); pg.wait_for_timeout(200); pg.screenshot(path=f'{OUT}/{tag}-8-lieu.png')
        pg.click('#voile [data-act=parler][data-id=melusine]'); pg.click('#voile [data-act=question][data-p=melusine][data-i="0"]'); pg.click('#voile [data-act=question][data-p=melusine][data-i="1"]')
        pg.wait_for_timeout(200); pg.screenshot(path=f'{OUT}/{tag}-9-conv.png')
        pg.click('#voile [data-act=demasquer]'); pg.wait_for_timeout(800); pg.screenshot(path=f'{OUT}/{tag}-10-mj-intro.png')
        print(tag, errs)
    b.close()
