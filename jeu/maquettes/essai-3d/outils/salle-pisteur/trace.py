# Chaque contour est relevé sur un gros plan quadrillé (zoom.py), en pixels DU GROS PLAN : (origine x, origine y, échelle, points).
# Chaque forme au sol est mesurée sur l'image (pied avant, largeur) ou donnée en pas quand elle touche un mur.
#   rond_img   = (u du centre, v du pied avant, demi-largeur en px)            -> un cylindre
#   boite_img  = (u gauche, u droite, v du pied avant, profondeur en pas)       -> une boîte
#   boites_img = plusieurs boîtes ; boite = (x0, x1, y0, y1) en pas du jeu (contre un mur, ou mesurée à la main)
#   h          = la hauteur en pas (sinon : calculée du haut du contour au pied)
#   muret      = on le saute ; mur = un morceau du mur du bas (profondeur de son devant)

def _z(o, pts):
    x0, y0, s = o
    return [(round(x0 + x / s, 1), round(y0 + y / s, 1)) for x, y in pts]

