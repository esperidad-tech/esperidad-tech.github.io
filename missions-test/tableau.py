"""Le tableau d'enquête du Sage, sur téléphone (390×844) : taper, recharger, accuser, passer de l'enquête 1 à la 2."""
import os, json
from playwright.sync_api import sync_playwright
URL = 'file://' + os.path.join(os.environ['BRUMEVAL_DIST'], 'index.html')
OUT = os.path.dirname(os.path.abspath(__file__)) + '/captures'
os.makedirs(OUT, exist_ok=True)
erreurs, echecs = [], []
def verif(c, msg):
    print(('  OK  ' if c else '  ✗✗ ') + msg, flush=True)
    if not c: echecs.append(msg)
def ev(pg, js): return pg.evaluate(js)
def nouveau(b, N=1):
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2)
    pg = ctx.new_page(); pg.set_default_timeout(30000)
    pg.on('console', lambda m: erreurs.append(f'[E{N}] {m.text}') if m.type == 'error' and 'ERR_' not in m.text and 'fonts' not in m.text else None)
    pg.on('pageerror', lambda e: erreurs.append(f'[E{N}] PAGEERROR {e}'))
    pg.add_init_script('window.BRUMEVAL_SANS_TUTO = true')   # ce banc teste d'autres systèmes : l'enquête 1 sans le tutoriel guidé (tools/tuto.py teste le tutoriel)
    pg.goto(URL)
    pg.click('[data-act=creer]'); pg.click('[data-act=crea-role][data-r=sage]'); pg.click('[data-act=crea-suite]')
    pg.fill('#nom', 'Sage'); pg.click('[data-act=crea-fin]')
    if N > 1:
        # (l'accueil d'un héros débutant n'a plus de bouton Réglages, Romain 4 novembre : on ouvre les Réglages directement pour le Mode test)
        pg.evaluate("() => { M.UI.ecran = 'reglages'; M.render(); }"); pg.click(f'[data-act=mode-test][data-i="{N}"]'); pg.click('#voile [data-act=confirmer-oui]')
    pg.click('[data-act=nouvelle-enquete]'); pg.click('[data-act=commencer]')
    pg.click('[data-act=onglet][data-o=role]'); pg.wait_for_timeout(300)
    livre(pg, 'tableau')
    return pg
def mesures(pg):
    return ev(pg, """() => { var b = document.querySelector('.tb-boite'), cs = [].slice.call(document.querySelectorAll('.tb-case')).map(function(c){ var r = c.getBoundingClientRect(); return [r.width, r.height]; });
      return {page:document.documentElement.scrollWidth, boite:b ? [b.scrollWidth, b.clientWidth] : null, min:cs.length ? [Math.min.apply(0, cs.map(function(x){ return x[0]; })), Math.min.apply(0, cs.map(function(x){ return x[1]; }))] : null, n:cs.length}; }""")
def livre(pg, page):
    if not pg.is_visible('#livre-ici'): pg.click('[data-act=onglet][data-o=role]'); pg.wait_for_timeout(300)
    pg.evaluate(f"() => M.livreAller('{page}', true)"); pg.wait_for_timeout(250)
def case(pg, k): pg.click(f'[data-act=tab-case][data-k="{k}"]'); pg.wait_for_timeout(120)
def tete(pg, d, i): pg.click(f'[data-act=tab-tete][data-d={d}][data-id="{i}"]'); pg.wait_for_timeout(120)

with sync_playwright() as p:
    b = p.chromium.launch()
    S = nouveau(b, 1)
    verif(S.is_visible('.tb-grille'), 'E1 : le Grand Livre s\'ouvre sur « Mon tableau d\'enquête »')
    verif(ev(S, "() => M.livreAller('tableau', true)"), 'E1 : le Grand Livre a la page « Mon tableau d\'enquête »')
    m = mesures(S); print('  mesures E1 :', m)
    verif(m['n'] == 24, 'E1 : 6 suspects × 4 lieux = 24 cases')
    verif(m['page'] <= 390, 'E1 : pas de défilement de côté sur la page')
    verif(m['boite'][0] <= m['boite'][1] + 1, 'E1 : la grille tient en largeur, sans défiler')
    verif(m['min'][0] >= 44 and m['min'][1] >= 44, f'E1 : cases d\'au moins 44 px ({m["min"]})')
    S.screenshot(path=f'{OUT}/tableau-E1-vide.png')
    case(S, 'tim|chene'); verif(ev(S, "() => M.P().tableau.cases['tim|chene']") == 'x', 'Case : 1 toucher = ✗')
    case(S, 'tim|chene'); verif(ev(S, "() => M.P().tableau.cases['tim|chene']") == 'v', 'Case : 2 touchers = ✓')
    case(S, 'tim|chene'); verif(ev(S, "() => !M.P().tableau.cases['tim|chene']") , 'Case : 3 touchers = vide')
    case(S, 'odette|puits'); case(S, 'melusine|toits'); case(S, 'melusine|toits')
    tete(S, 'qui', 'gaspard'); verif(ev(S, "() => M.P().tableau.dims.qui.gaspard === 'x' && M.P().raye.indexOf('gaspard') < 0"), 'Visage touché : Gaspard barré (dans le tableau seulement)')
    tete(S, 'qui', 'basile'); tete(S, 'qui', 'basile'); verif(ev(S, "() => M.P().tableau.dims.qui.basile === 'v'"), 'Visage touché deux fois : Basile « sûr » ✓')
    tete(S, 'ou', 'puits'); verif(ev(S, "() => M.P().tableau.dims.ou.puits") == 'x', 'Lieu touché : le puits barré')
    S.evaluate("() => window.scrollTo(0, 0)"); S.screenshot(path=f'{OUT}/tableau-E1-marques.png')
    S.screenshot(path=f'{OUT}/tableau-E1-marques-page.png', full_page=True)
    # Carnet : on ne raye plus rien là-bas (les visages s'ouvrent), le tableau garde ses marques
    S.click('[data-act=onglet][data-o=carnet]'); S.wait_for_timeout(200)
    verif(S.locator('[data-act=rayer], [data-act=carnet-pnj], .cn-gens').count() == 0 and S.locator('.b-missions').count() == 1 and S.locator('.cn-indices').count() == 1, 'Carnet du Sage : missions + « Mes indices », ni visages ni suspects')
    S.click('[data-act=onglet][data-o=role]'); S.wait_for_timeout(200); livre(S, 'tableau')
    verif(S.locator('.tb-ligne.tb-x[data-id=gaspard]').count() == 1, 'Tableau : Gaspard toujours barré après un tour au Carnet')
    # Accusation : barrés grisés, mais choisissables
    livre(S, 'accusation'); S.click('[data-act=accuser]'); S.wait_for_timeout(200)
    verif(S.locator('#voile .b-suspect.raye[data-v=gaspard]').count() == 1, 'Accusation : Gaspard grisé')
    S.screenshot(path=f'{OUT}/tableau-E1-accusation-qui.png')
    S.click('#voile [data-act=acc-choix][data-k=qui][data-v=gaspard]'); S.wait_for_timeout(150)
    verif(S.locator('#voile .b-lieu-acc.raye[data-v=puits]').count() == 1, 'Accusation : le puits grisé (et Gaspard restait choisissable)')
    S.screenshot(path=f'{OUT}/tableau-E1-accusation-ou.png')
    S.evaluate("() => { M.UI.modal = null; M.render(); }"); livre(S, 'tableau')
    # Tout effacer : demande confirmation (on dit non)
    S.click('[data-act=tab-effacer]'); S.wait_for_timeout(150)
    verif(S.is_visible('#voile [data-act=confirmer-oui]'), '« Tout effacer » demande confirmation')
    S.evaluate("() => { M.UI.modal = null; M.UI.confirmer = null; M.render(); }")
    # Recharger : les marques restent
    avant = ev(S, "() => JSON.stringify([M.P().tableau, M.P().raye])")
    S.reload(); S.wait_for_timeout(500)
    if S.is_visible('[data-act=reprendre]'): S.click('[data-act=reprendre]')
    S.click('[data-act=onglet][data-o=role]'); S.wait_for_timeout(300); livre(S, 'tableau')
    apres = ev(S, "() => JSON.stringify([M.P().tableau, M.P().raye])")
    verif(avant == apres and S.locator('.tb-case.tb-x').count() >= 1, 'Après rechargement : toutes les marques sont là')
    # Gagner l'enquête 1 et passer à la 2 : le tableau de l'enquête 1 reste dans le journal
    sol = ev(S, "() => M.E().solution")
    livre(S, 'accusation'); S.click('[data-act=accuser]')
    S.click(f'#voile [data-act=acc-choix][data-k=qui][data-v={sol["qui"]}]'); S.click(f'#voile [data-act=acc-choix][data-k=ou][data-v={sol["ou"]}]')
    S.click('#voile [data-act=acc-valider]'); S.wait_for_timeout(300)
    S.click('#voile [data-act=fin-sage]'); S.wait_for_timeout(300)
    for i in range(14):
        if S.is_visible('[data-act=fin-suite]'): S.click('[data-act=fin-suite]'); S.wait_for_timeout(60)
    S.click('[data-act=suite-sage]'); S.wait_for_timeout(300)
    if S.is_visible('#voile .b-fermer'): S.click('#voile .b-fermer')
    verif(ev(S, "() => M.P().id") == 2, 'Le Sage est passé à l\'enquête 2')
    S.click('[data-act=commencer]'); S.wait_for_timeout(200)
    verif(ev(S, "() => !M.P().tableau || !Object.keys(M.P().tableau.cases || {}).length"), 'Enquête 2 : tableau neuf, vide')
    S.click('[data-act=onglet][data-o=carnet]'); S.wait_for_timeout(200)
    S.click('[data-act=journal][data-e="1"]'); S.wait_for_timeout(300)
    verif(S.is_visible('.b-tb-journal .tb-grille') and S.locator('.b-tb-journal .tb-case.tb-x').count() >= 1, 'Journal « Enquête 1 » : le tableau de l\'enquête 1 est gardé, en lecture seule')
    verif(S.locator('.b-tb-journal [data-act]').count() == 0, 'Journal : pas de bouton dans le tableau passé')
    S.screenshot(path=f'{OUT}/tableau-journal-E1.png')
    S.click('[data-act=onglet][data-o=role]'); S.wait_for_timeout(300); livre(S, 'tableau')
    m = mesures(S); print('  mesures E2 :', m)
    # la nouvelle enquête 2 (§ 12.11) : 5 suspects × 5 lieux, plus la rangée « POURQUOI » (4 raisons) ; l'enquête 3 est en cours d'écriture
    verif(m['n'] == 25 and m['page'] <= 390 and m['boite'][0] <= m['boite'][1] + 1, 'E2 : 5 × 5, ça tient sans défiler de côté')
    verif(S.locator('.tb-plus .tb-puce').count() == 4, 'E2 : rangée « POURQUOI » avec 4 raisons')
    S.click('[data-act=tab-tete][data-d=pourquoi][data-id=farce]'); S.wait_for_timeout(150)
    S.click('[data-act=tab-tete][data-d=pourquoi][data-id=paye]'); S.click('[data-act=tab-tete][data-d=pourquoi][data-id=paye]'); S.wait_for_timeout(150)
    verif(ev(S, "() => JSON.stringify(M.P().tableau.dims.pourquoi)") == '{"farce":"x","paye":"v"}', 'E2 : marques sur la question « POURQUOI »')
    S.evaluate("() => window.scrollTo(0, 0)"); S.screenshot(path=f'{OUT}/tableau-E2.png', full_page=True)
    S.evaluate("() => { var P = M.P(); P.aube = true; ['info:odette', 'info:canne', 'obj:pierre'].forEach(function(c){ P.recus[c] = true; }); M.sauver(); M.render(); }")   # le verrou de l'accusation (regles.js) ouvert
    livre(S, 'accusation'); S.click('[data-act=accuser]'); S.click('#voile [data-act=acc-choix][data-k=qui][data-v=bastien]'); S.click('#voile [data-act=acc-choix][data-k=ou][data-v=moulin]'); S.wait_for_timeout(150)
    verif(S.locator('#voile .b-lieu-acc.raye[data-v=farce]').count() == 1, 'E2 accusation : « pour faire une farce » grisé à « POURQUOI »')
    S.screenshot(path=f'{OUT}/tableau-E2-accusation-pourquoi.png')
    print('ERREURS :', erreurs)
    print('ÉCHECS :', echecs)
    b.close()
