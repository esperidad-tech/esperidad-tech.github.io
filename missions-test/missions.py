    verif(P.locator('.cn-ev-obj:has-text("fil de laine rouge") .b-code, .cn-ev-obj:has-text("Fil de laine rouge") .b-code').count() >= 1 and 'pour l\'Alchimiste' in fil, 'Fil : le fil rouge trouvé, avec son code et pour qui (l\'Alchimiste)')
    verif('Course-poursuite perdue' in fil and 'Course-poursuite gagnée' in fil, 'Fil : la course-poursuite perdue puis gagnée')
    verif('Passage ouvert' in fil and 'Code reçu' in fil, 'Fil : le code reçu et la forêt qui s\'ouvre')
