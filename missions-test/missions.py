    S.click('[data-act=onglet][data-o=role]'); S.wait_for_timeout(300); S.evaluate("() => M.livreAller('habitants', true)"); S.wait_for_timeout(700)
    verif(S.is_visible('.tu-bandeau [data-act=tuto-fait]'), 'Sage (tutoriel) : sur la page « Les habitants », le bandeau propose « ✔ C\'est fait »')
