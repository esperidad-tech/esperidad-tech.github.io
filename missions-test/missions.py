    entrer(B, 'obj:affiche')
    plein(B); act(B, 'parler', {'id': 'gaspard'}); question(B, 'gaspard', 1)
    verif(faits(B)[:5] == '✅✅✅✅✅', 'Barde : mission « montre l\'affiche à Gaspard » validée')
    # --- Pisteur : le code du chemin de Basile ouvre la forêt
    entrer(P, 'info:chemin')
    verif(faits(P)[:6] == '✅✅✅✅✅✅', 'Pisteur : mission « entre dans la forêt » validée avec le code de Basile')
