"""Missions de base de l'enquête 1 : chaque mission se valide en jouant vraiment (4 écrans, 390×844).
Les mini-jeux sont court-circuités (réussis) ; l'atelier est ouvert au doigt (on touche un carton)."""
import os, json
from playwright.sync_api import sync_playwright
DIST = os.environ['BRUMEVAL_DIST']
URL = 'file://' + os.path.join(DIST, 'index.html')
OUT = os.path.dirname(os.path.abspath(__file__)) + '/captures'
os.makedirs(OUT, exist_ok=True)
erreurs, echecs = [], []
def verif(c, msg):
    print(('  OK  ' if c else '  ✗✗ ') + msg, flush=True)
    if not c: echecs.append(msg)
def creer(b, role):
    pg = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2).new_page()
    pg.set_default_timeout(30000)
    pg.on('console', lambda m: erreurs.append(f'[{role}] {m.text}') if m.type == 'error' and 'ERR_' not in m.text and 'fonts' not in m.text else None)
    pg.on('pageerror', lambda e: erreurs.append(f'[{role}] PAGEERROR {e}'))
    pg.goto(URL)
    pg.click('[data-act=creer]'); pg.click(f'[data-act=crea-role][data-r={role}]'); pg.click('[data-act=crea-hasard]'); pg.click('[data-act=crea-suite]')
    pg.fill('#nom', role.capitalize())
    pg.click('[data-act=crea-fin]')
    pg.click('[data-act=nouvelle-enquete]')
    pg.wait_for_timeout(300)
    pg.screenshot(path=f'{OUT}/{role}-0-lettre.png', full_page=True)
    pg.click('[data-act=commencer]')
    pg.evaluate("""() => { MJ.lancer = function(el, type, params, fin){ setTimeout(function(){ fin({reussi:true, score:1, essais:1}); }, 30); return {arreter:function(){}}; }; }""")
    return pg
def ev(pg, js): return pg.evaluate(js)
def act(pg, a, data): pg.evaluate(f"() => M.A['{a}']({{dataset:{json.dumps(data)}}})"); pg.wait_for_timeout(120)
def fermer(pg): pg.evaluate("() => { M.UI.modal = null; M.render(); }")
def plein(pg): pg.evaluate("() => { M.P().actions = 9; }")
def faits(pg): return ev(pg, "() => { var L = M.etapesMission(), Mi = M.P().mission || {faits:{}}; return L.map(function(e, i){ return e.libre ? '·' : (Mi.faits[i] ? '✅' : '⬜'); }).join(''); }")
def badge(pg): return ev(pg, "() => !!document.querySelector('.b-onglets [data-o=carnet] .b-badge-mission')")
def carnet(pg, nom):
    pg.click('[data-act=onglet][data-o=carnet]'); pg.wait_for_timeout(250)
    pg.screenshot(path=f'{OUT}/{nom}.png', full_page=True)
def entrer(pg, code):
    for s in ev(pg, f"() => M.code('{code}')"): act(pg, 'sym', {'s': s})
    pg.wait_for_timeout(400); fermer(pg)
def explorer(pg, lieu, points):
    plein(pg); act(pg, 'explorer', {'id': lieu})
    for p in points: act(pg, 'point', {'l': lieu, 'id': p}); pg.wait_for_timeout(150); fermer(pg)
def question(pg, pnj, i): act(pg, 'question', {'p': pnj, 'i': str(i)}); fermer(pg)

