    question(B, 'odette', 3)
    verif(faits(B)[:2] == '✅✅', 'Barde : mission Odette validée (toutes ses questions)')
    plein(B); act(B, 'parler', {'id': 'basile'}); question(B, 'basile', 2)
    verif(faits(B)[:3] == '✅✅✅', 'Barde : mission Basile (la forêt) validée')
    entrer(B, 'moment:1')   # (tutoriel) Mélusine, c'est l'après-midi, sur la place
    plein(B); act(B, 'parler', {'id': 'melusine'}); question(B, 'melusine', 1); question(B, 'melusine', 2)
