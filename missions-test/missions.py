    verif(faits(S)[1] == '⬜', 'Sage : la recette n\'est pas validée d\'avance')
    act(S, 'page', {'id': 'recettes'}); S.click('[data-act=onglet][data-o=carnet]'); S.wait_for_timeout(300)
    verif(faits(S)[:2] == '✅✅', 'Sage : « Lis la recette » validée quand la page « Les recettes » est ouverte')
    # une piste se coche et se décoche à la main
    S.click('.b-missions [data-act=mission-coche][data-i="5"]'); S.wait_for_timeout(200)
    verif(ev(S, "() => !!M.P().mission.coches[5]") and S.locator('.b-missions li.piste.coche').count() == 1, 'Sage : la piste se coche à la main')
    S.click('.b-missions [data-act=mission-coche][data-i="5"]'); S.wait_for_timeout(200)
    verif(ev(S, "() => !M.P().mission.coches[5]") and S.locator('.b-missions li.piste.coche').count() == 0, 'Sage : … et se décoche')
    verif('Piste :' in S.inner_text('.b-missions li.piste'), 'Sage : la ligne « Piste : … » est là')
    # --- Sage : le balcon de la mairie
    plein(S); act(S, 'explorer', {'id': 'mairie'}); act(S, 'point', {'l': 'mairie', 'id': 'balcon'}); fermer(S)
    verif(faits(S)[:3] == '✅✅✅', 'Sage : mission balcon de la mairie validée')
    # --- Pisteur : tutoriel, endroit par endroit
    verif(ev(P, "() => M.missionsLieux().map(function(x){ return x.lieu.join('|') + (x.courante ? '*' : ''); }).join(',')") == 'mairie*,mairie,mairie,place,boulangerie,foret,foret,foret,chene', 'Pisteur : M.missionsLieux() donne les endroits dans l\'ordre (mairie en cours)')
    verif(ev(P, "() => M.pointsVisibles('place', 'pisteur').every(function(p){ return p.id !== 'plantes'; })"), 'Pisteur E1 : « Ce qui pousse ici » caché au début')
    P.click('[data-act=onglet][data-o=carte]'); P.wait_for_timeout(200)
    explorer(P, 'mairie', ['massif'])
    verif(faits(P)[:1] == '✅', 'Pisteur : massif (traces) validé')
    act(P, 'point', {'l': 'mairie', 'id': 'fenetre'}); fermer(P); act(P, 'point', {'l': 'mairie', 'id': 'gouttiere'}); fermer(P)
    verif(faits(P)[:3] == '✅✅✅', 'Pisteur : fenêtre et gouttière validées')
    verif(badge(P), 'Pisteur : pastille 🎯 après une mission validée')
    verif(ev(P, "() => M.missionsLieux()[3].courante"), 'Pisteur : la place devient la mission en cours')
    explorer(P, 'place', ['fontaine', 'affiche'])
    explorer(P, 'boulangerie', ['sol', 'four'])
    verif(faits(P)[4] == '⬜' and ev(P, "() => M.tutoGuide().etat") == 'moment', 'Pisteur (tutoriel) : la boulangerie attend l\'après-midi')
    entrer(P, 'moment:1')
    explorer(P, 'boulangerie', ['sol', 'four'])
    verif(faits(P)[:5] == '✅✅✅✅✅', 'Pisteur : place et boulangerie validées')
    # --- Barde : noter une maison, Odette, Basile (le chemin), Mélusine, Gaspard (l'affiche)
    B.evaluate("() => { M.A['noter-maison']({dataset:{m:'L2', id:'odette'}}); }"); B.wait_for_timeout(200)
    verif(faits(B)[0] == '✅', 'Barde : mission « note qui habite où » validée')
    plein(B); act(B, 'frapper', {'id': 'L2'}); question(B, 'odette', 1); question(B, 'odette', 2)
