    P.click('[data-act=onglet][data-o=carnet]'); P.wait_for_timeout(300)
    verif(P.is_visible('.b-missions') and P.is_visible('.cn-aventure') and P.locator('.cn-gens, .cn-indices, [data-act=carnet-pnj], [data-act=rayer]').count() == 0, 'Pisteur : Carnet = missions + fil d\'aventure, sans visages ni « Mes indices »')
